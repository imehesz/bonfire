const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// `active` = [start, end] character ranges to light up (the steps playing right now).
export function highlight(code, active = []) {
  const re = /(\/\/[^\n]*)|("(?:[^"\\]|\\.)*")|('(?:[^'\\]|\\.)*')|(\.[a-zA-Z_]\w*)(?=\()|\b(const|x)\b|(\b\d+(?:\.\d+)?\b)|([a-zA-Z_]\w*)(?=\()|(=>)/g;
  const on = new Uint8Array(code.length);
  for (const [a, b] of active) on.fill(1, Math.max(0, a), Math.min(code.length, b));
  // one token, split into runs where the lit state changes
  const span = (from, to, cls) => {
    let out = '';
    for (let i = from; i < to;) {
      let j = i + 1;
      while (j < to && on[j] === on[i]) j++;
      const c = on[i] ? `${cls} tk-on`.trim() : cls;
      out += c ? `<span class="${c}">${esc(code.slice(i, j))}</span>` : esc(code.slice(i, j));
      i = j;
    }
    return out;
  };
  let out = '';
  let last = 0;
  for (const m of code.matchAll(re)) {
    out += span(last, m.index, '');
    const [t, com, dq, sq, meth, kw, numb, fn, arrow] = m;
    const cls = com ? 'tk-com' : dq ? 'tk-mini' : sq ? 'tk-str' : meth ? 'tk-meth' : kw ? 'tk-kw' : numb ? 'tk-num' : fn ? 'tk-fn' : arrow ? 'tk-kw' : '';
    out += span(m.index, m.index + t.length, cls);
    last = m.index + t.length;
  }
  return out + span(last, code.length, '');
}

export function mountInspector(host) {
  const pre = h('pre', { class: 'code' });
  const status = h('div', { class: 'insp-status' });
  const lines = h('span', { class: 'insp-lines' });
  let code = '';
  let shareLink = '';
  let litKey = '';
  let playing = false;
  let collapsed = false;
  let side = 'bottom';
  let tab = 'code';
  try {
    collapsed = localStorage.getItem('bonfire.inspector') === 'closed';
    side = localStorage.getItem('bonfire.dock') === 'right' ? 'right' : 'bottom';
    tab = ['modcons', 'samples'].includes(localStorage.getItem('bonfire.dockTab')) ? localStorage.getItem('bonfire.dockTab') : 'code';
  } catch { /* ignore */ }
  const modcons = mountModcons();
  const samples = mountSamples();
  // user-dragged dock size in px (null = the CSS default); CSS caps it at half the screen
  const DEFAULT_SIZE = { bottom: 220, right: 440 };
  let size = { bottom: null, right: null };
  try {
    size = { ...size, ...JSON.parse(localStorage.getItem('bonfire.dockSize') ?? '{}') };
  } catch { /* ignore */ }
  const applySize = () => {
    const b = document.body.style;
    if (size.bottom) b.setProperty('--insp-h', `min(${size.bottom}px, 50vh)`);
    else b.removeProperty('--insp-h');
    if (size.right) b.setProperty('--insp-w', `min(${size.right}px, 50vw)`);
    else b.removeProperty('--insp-w');
  };
  applySize();
  const exported = () => [`// made with Bonfire STACK: ${SITE}`, LOGO, '', code,
    ...(shareLink ? ['', `// open this patch in Bonfire STACK: ${shareLink}`] : [])].join('\n');
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(exported());
      toast('Code copied — paste it into strudel.cc');
    } catch {
      toast('Clipboard blocked by the browser', 'warn');
    }
  };
  const open = () => window.open(`https://strudel.cc/#${code2hash(exported())}`, '_blank', 'noopener');
  const toggleBtn = h('button', { class: 'insp-toggle', title: 'Show / hide code' });
  const dock = h('section', { class: 'inspector' },
    h('header', {},
      toggleBtn,
      h('span', { class: 'insp-title', dataset: { tab: 'code' } }, 'STRUDEL CODE'),
      h('span', { class: 'insp-title', dataset: { tab: 'modcons' }, title: 'Module connections: click a module in the rack' }, 'MODCONS'),
      h('span', { class: 'insp-title', dataset: { tab: 'samples' }, title: 'Sounds, sample packs and your own files' }, 'SAMPLES'),
      lines,
      status,
      h('div', { class: 'insp-actions' },
        h('button', { class: 'btn', onclick: copy }, 'COPY CODE'),
        h('button', { class: 'btn accent', onclick: open, title: 'Opens this exact code in the strudel.cc REPL' }, 'OPEN IN STRUDEL ↗'))),
    h('div', { class: 'insp-body' }, pre, modcons.el, samples.el));
  // drag the inner edge to resize, from the default up to half the screen; double-click resets
  const grip = h('div', { class: 'insp-grip', title: 'Drag to resize · double-click to reset' });
  dock.prepend(grip);
  const saveSize = () => {
    try {
      localStorage.setItem('bonfire.dockSize', JSON.stringify(size));
    } catch { /* ignore */ }
    window.dispatchEvent(new Event('resize')); // cables re-measure jack positions
  };
  grip.addEventListener('pointerdown', (e) => {
    if (e.button !== 0) return;
    e.preventDefault();
    grip.setPointerCapture(e.pointerId);
    document.body.classList.add('dock-resizing');
    const move = (ev) => {
      const px = side === 'right' ? window.innerWidth - ev.clientX : window.innerHeight - ev.clientY;
      const max = (side === 'right' ? window.innerWidth : window.innerHeight) / 2;
      size[side] = Math.round(Math.min(max, Math.max(DEFAULT_SIZE[side], px)));
      applySize();
    };
    const up = () => {
      grip.removeEventListener('pointermove', move);
      grip.removeEventListener('pointerup', up);
      grip.removeEventListener('pointercancel', up);
      document.body.classList.remove('dock-resizing');
      saveSize();
    };
    grip.addEventListener('pointermove', move);
    grip.addEventListener('pointerup', up);
    grip.addEventListener('pointercancel', up);
  });
  grip.addEventListener('dblclick', () => {
    size[side] = null;
    applySize();
    saveSize();
  });
  // Body classes let the rack and drawers make room for the dock.
  const setCollapsed = (v) => {
    collapsed = v;
    dock.classList.toggle('collapsed', v);
    document.body.classList.toggle('insp-collapsed', v);
    toggleBtn.textContent = side === 'right' ? (v ? '◀' : '▶') : (v ? '▲' : '▼');
    try {
      localStorage.setItem('bonfire.inspector', v ? 'closed' : 'open');
    } catch { /* ignore */ }
  };
  toggleBtn.onclick = () => setCollapsed(!collapsed);
  const setTab = (t) => {
    tab = t;
    dock.dataset.tab = t;
    for (const el of dock.querySelectorAll('.insp-title')) el.classList.toggle('on', el.dataset.tab === t);
    litKey = ''; // the code may have changed while hidden
    if (t === 'samples') samples.render();
    try {
      localStorage.setItem('bonfire.dockTab', t);
    } catch { /* ignore */ }
  };
  // clicking the open tab folds the dock; another tab switches to it (and unfolds)
  for (const el of dock.querySelectorAll('.insp-title')) {
    el.onclick = () => {
      if (el.dataset.tab === tab) return setCollapsed(!collapsed);
      setTab(el.dataset.tab);
      if (collapsed) setCollapsed(false);
    };
  }
  setTab(tab);
  const setDock = (s) => {
    side = s;
    document.body.classList.toggle('dock-right', s === 'right');
    setCollapsed(collapsed);
    try {
      localStorage.setItem('bonfire.dock', s);
    } catch { /* ignore */ }
    window.dispatchEvent(new Event('resize')); // cables re-measure jack positions
  };
  setDock(side);
  host.append(dock);
  // light up the steps that are sounding; only re-render when the lit set changes
  const render = (ranges) => {
    const key = ranges.map((r) => r.join('-')).sort().join(',');
    if (key === litKey) return;
    litKey = key;
    pre.innerHTML = highlight(code, ranges);
  };
  const tick = () => {
    requestAnimationFrame(tick);
    if (collapsed || tab !== 'code' || document.hidden) return;
    render(playing ? activeRanges(code) : []);
  };
  requestAnimationFrame(tick);
  return {
    dockSide: () => side,
    setDock,
    setShareLink(url) {
      shareLink = url;
    },
    setCode(c) {
      if (c === code) return;
      code = c;
      litKey = '';
      pre.innerHTML = highlight(c);
      lines.textContent = `${c.split('\n').length} lines`;
    },
    setStatus({ error, playing: p, loading, compileErrors = [] }) {
      playing = p;
      const err = error || compileErrors.join(' · ');
      status.className = `insp-status ${err ? 'err' : p ? 'live' : ''}`;
      status.textContent = err ? `⚠ ${err}` : loading ? 'loading sounds…' : p ? '● LIVE' : '■ STOPPED';
    },
  };
}
